/**
 * Dashboard entry point — mounts the React app with TanStack Router + Query providers.
 * Purpose: bootstraps the SPA for the Lore read-only dashboard.
 * Invariants:
 *   - bootstrapAuthIfNeeded() runs before React mounts (top-level await).
 *   - Bootstrap failure is non-fatal: shows a sonner toast but renders anyway.
 *   - Single DOM mount point (#root). Only pure reads; no write operations.
 * Side-effect class: IO (DOM mount, router initialization, optional fetch for auth bootstrap)
 * Source: SPEC-015 §3; SPEC-016 §3.8
 */

import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { RouterProvider, createRouter } from "@tanstack/react-router";
import { QueryClientProvider } from "@tanstack/react-query";
import { toast } from "sonner";
import { routeTree } from "./routeTree.gen";
import { queryClient } from "./lib/query-client";
import { ThemeProvider } from "./lib/theme";
import { Toaster } from "./components/ui/sonner";
import { bootstrapAuthIfNeeded } from "./lib/bootstrap";
import "./index.css";

// ─── Auth bootstrap (SPEC-016 §3.8) ──────────────────────────────────────────

// reason: bootstrapAuthIfNeeded() must run BEFORE createRoot().render() so the session
// cookie is set before any API fetch is issued by route components. Top-level await is
// supported in Vite ES module entry points. SPEC-016 §3.8.
try {
  await bootstrapAuthIfNeeded();
} catch (err: unknown) {
  // Non-fatal: render the app anyway. The session cookie was not set — API calls will
  // fail with 401 until the user restarts `lore dashboard`. The toast informs them.
  const message = err instanceof Error ? err.message : String(err);
  // reason: toast.error() is queued here before Toaster mounts. sonner buffers toasts
  // and displays them once <Toaster /> is in the DOM. SPEC-016 §3.8.
  toast.error(`Auth bootstrap failed: ${message}. Restart with \`lore dashboard\`.`);
}

// ─── Router ───────────────────────────────────────────────────────────────────

// Create the router instance with the auto-generated route tree.
// reason: file-based routing requires routeTree.gen.ts (auto-generated by TanStack Router Vite
// plugin on dev start or via `bunx @tanstack/router-cli generate`). See SPEC-015 §4 M4.
const router = createRouter({
  routeTree,
  defaultPreload: "intent",
});

// Register the router instance for type safety.
declare module "@tanstack/react-router" {
  interface Register {
    router: typeof router;
  }
}

// ─── Mount ────────────────────────────────────────────────────────────────────

const rootElement = document.getElementById("root");
if (rootElement === null) {
  throw new Error("Root element #root not found in index.html");
}

createRoot(rootElement).render(
  <StrictMode>
    <QueryClientProvider client={queryClient}>
      <ThemeProvider>
        {/* reason: Toaster must be inside providers so it inherits theme. Queued toasts
            (e.g. bootstrap failure before mount) are displayed once this mounts. SPEC-016 §3.8. */}
        <Toaster />
        <RouterProvider router={router} />
      </ThemeProvider>
    </QueryClientProvider>
  </StrictMode>,
);
