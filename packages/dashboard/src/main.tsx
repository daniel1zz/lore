/**
 * Dashboard entry point — mounts the React app with TanStack Router + Query providers.
 * Purpose: bootstraps the SPA for the Lore read-only dashboard.
 * Invariants: single DOM mount point (#root). Only pure reads; no write operations.
 * Side-effect class: IO (DOM mount, router initialization)
 */

import { StrictMode } from "react";
import { createRoot } from "react-dom/client";
import { RouterProvider, createRouter } from "@tanstack/react-router";
import { QueryClientProvider } from "@tanstack/react-query";
import { routeTree } from "./routeTree.gen";
import { queryClient } from "./lib/query-client";
import { ThemeProvider } from "./lib/theme";
import "./index.css";

// Create the router instance with the auto-generated route tree.
// reason: file-based routing requires routeTree.gen.ts (auto-generated by TanStack Router Vite
// plugin on dev start or via `bunx @tanstack/router-cli generate`). See SPEC-015 §4 M4.
const router = createRouter({
  routeTree,
  defaultPreload: "intent",
});

// Register the router instance for type safety.
declare module "@tanstack/react-router" {
  interface Register {
    router: typeof router;
  }
}

const rootElement = document.getElementById("root");
if (rootElement === null) {
  throw new Error("Root element #root not found in index.html");
}

createRoot(rootElement).render(
  <StrictMode>
    <QueryClientProvider client={queryClient}>
      <ThemeProvider>
        <RouterProvider router={router} />
      </ThemeProvider>
    </QueryClientProvider>
  </StrictMode>,
);
