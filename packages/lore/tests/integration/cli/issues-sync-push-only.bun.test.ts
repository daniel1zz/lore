/**
 * @spec_ref spec-github-owns-issue-report-state-no-mirror-task-work-carries#AC-GS-16
 * @task task-skill-refactor-gs-t5-lore-issues-live-only-push-only-sync
 *
 * `lore issues --sync` is the PUSH-ONLY repair: it closes `fixed (close pending)` issues, converges
 * `resolution:fixed`, strips `resolution:*` labels from open issues, writes nothing to the corpus, and prints
 * `clean` only after a COMPLETE (every page read) listing showed nothing to repair.
 *
 * Oracle: the real command tree (`runLoreInProcess`) over a throwaway corpus (`mkdtemp` + `lore init`) and a STUB
 * `gh` first on PATH. The stub serves a TWO-PAGE listing (`Link: rel="next"`), keeps per-issue state in files,
 * logs every argv, and never reaches GitHub. The carriers are written through the service (`create task --issue`)
 * and archived through `lore done`.
 *
 * Fixture (the spec's): #40 on page 2, open, named by an archived task (its close failed at archive time);
 * #41 open with labels resolution:adopted and resolution:fixed and no carrier; #42 closed/completed with a
 * verified archived carrier.
 *
 * Six-dimension note:
 *   HAPPY      run 1 exits 0; the stub log shows for #40 one PATCH closed/completed, one comment and one
 *              resolution:fixed label write; for #41 both labels deleted; for #42 nothing; listing requests == pages (2).
 *   NEGATIVE   #42 (already fixed and labelled) gets no write at all.
 *   BOUNDARY   #40 sits on page 2, so a sync that read page 1 only would miss it (the measured contradiction).
 *   STATE      run 2 prints `clean`, exits 0 and makes zero writes (idempotent); the corpus holds no new document.
 *   ERROR      page 2 failing as a network error: exit exactly 9 and stdout does not contain `clean`.
 *   REGRESSION the red-once mutation: printing `clean` when the planned list is empty regardless of whether the
 *              listing was complete (a swallowed listing failure becomes an empty listing).
 */

import { patchLoreConfig } from "../../helpers/patch-lore-config.js";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { appendFileSync, chmodSync, existsSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { FIXTURE_HOME_OUTSIDE_REPO, makeCleanTreeRepo } from "../../helpers/clean-tree-repo";
import { runLoreInProcess } from "../../helpers/run-lore-in-process";

const SPEC = "spec-github-owns-issue-report-state-no-mirror-task-work-carries";
const FAKE_REPO = "acme/widget";
const REPO_ID = 4242;

interface RunResult {
  readonly stdout: string;
  readonly stderr: string;
  readonly exitCode: number;
}

interface Fixture {
  readonly dir: string;
  readonly stubDir: string;
}

const dirsToClean: string[] = [];
afterAll(() => {
  for (const dir of dirsToClean) rmSync(dir, { recursive: true, force: true });
});

/**
 * The stub `gh`. Per-issue state lives beside it: `state-<n>`, `reason-<n>`, `labels-<n>` (one name per line);
 * `page-1.json` / `page-2.json` are the listing pages (regenerated by the test from those files);
 * `fail-patch-<n>` makes that issue's close PATCH fail as a network error; `fail-page-2` makes page 2 fail as one.
 */
function writeStubGh(stubDir: string): void {
  const script = `#!/bin/sh
D="${stubDir}"
echo "$*" >> "$D/gh.log"
if [ "$1" != "api" ]; then echo "stub gh: unexpected call: $*" >&2; exit 99; fi
path="$2"
method=GET
prev=""
lbl=""
for a in "$@"; do
  if [ "$prev" = "-X" ]; then method="$a"; fi
  case "$a" in
    labels*=*) lbl="\${a#*=}" ;;
  esac
  prev="$a"
done
if [ "$path" = "user" ]; then printf '%s\\n' '{"login":"stub-user"}'; exit 0; fi
if [ "$path" = "repos/${FAKE_REPO}" ]; then printf '%s\\n' '{"id":${REPO_ID},"name":"widget"}'; exit 0; fi
case "$path" in
  "repos/${FAKE_REPO}/issues?"*"page=1")
    printf 'HTTP/2.0 200 OK\\nLink: <https://api.github.com/repositories/${REPO_ID}/issues?state=all&per_page=100&page=2>; rel="next"\\n\\n'
    cat "$D/page-1.json"
    exit 0 ;;
  "repos/${FAKE_REPO}/issues?"*"page=2")
    if [ -f "$D/fail-page-2" ]; then echo "error connecting to api.github.com: could not resolve host: api.github.com" >&2; exit 1; fi
    printf 'HTTP/2.0 200 OK\\n\\n'
    cat "$D/page-2.json"
    exit 0 ;;
esac
n=$(printf '%s' "$path" | sed -E 's#^repos/${FAKE_REPO}/issues/([0-9]+).*#\\1#')
labels_json() {
  out=""
  if [ -f "$D/labels-$n" ]; then
    while read -r name; do
      [ -z "$name" ] && continue
      if [ -z "$out" ]; then out="{\\"name\\":\\"$name\\"}"; else out="$out,{\\"name\\":\\"$name\\"}"; fi
    done < "$D/labels-$n"
  fi
  printf '[%s]' "$out"
}
case "$path" in
  "repos/${FAKE_REPO}/issues/$n")
    if [ "$method" = "PATCH" ]; then
      if [ -f "$D/fail-patch-$n" ]; then echo "error connecting to api.github.com: could not resolve host: api.github.com" >&2; exit 1; fi
      printf 'closed' > "$D/state-$n"
      printf 'completed' > "$D/reason-$n"
      printf '%s\\n' '{}'
      exit 0
    fi
    state=open
    [ -f "$D/state-$n" ] && state=$(cat "$D/state-$n")
    reason=null
    [ -f "$D/reason-$n" ] && reason="\\"$(cat "$D/reason-$n")\\""
    printf '{"state":"%s","state_reason":%s,"labels":%s}\\n' "$state" "$reason" "$(labels_json)"
    exit 0 ;;
  "repos/${FAKE_REPO}/issues/$n/comments")
    printf '%s\\n' '{}'
    exit 0 ;;
  "repos/${FAKE_REPO}/issues/$n/labels")
    if [ "$method" = "POST" ]; then
      printf '%s\\n' "$lbl" >> "$D/labels-$n"
      printf '%s\\n' '[]'
      exit 0
    fi
    printf '%s\\n' "$(labels_json)"
    exit 0 ;;
  "repos/${FAKE_REPO}/issues/$n/labels/"*)
    gone=$(printf '%s' "\${path##*/labels/}" | sed 's/%3A/:/g')
    grep -v -x -F "$gone" "$D/labels-$n" > "$D/labels-$n.tmp"
    mv "$D/labels-$n.tmp" "$D/labels-$n"
    exit 0 ;;
esac
echo "stub gh: unrecognised api path: $path" >&2
exit 99
`;
  const ghPath = join(stubDir, "gh");
  writeFileSync(ghPath, script);
  chmodSync(ghPath, 0o755);
}

function readLines(path: string): string[] {
  return existsSync(path) ? readFileSync(path, "utf8").split("\n").filter((line) => line !== "") : [];
}

/** Rewrites page-1/page-2 from the per-issue state files (the stub mutates those; the listing must follow). */
function regenerateListing(stubDir: string): void {
  const entry = (n: number): Record<string, unknown> => {
    const stateFile = join(stubDir, `state-${n}`);
    const reasonFile = join(stubDir, `reason-${n}`);
    return {
      number: n,
      title: `Issue ${n}`,
      state: existsSync(stateFile) ? readFileSync(stateFile, "utf8").trim() : "open",
      body: "",
      labels: readLines(join(stubDir, `labels-${n}`)).map((name) => ({ name })),
      state_reason: existsSync(reasonFile) ? readFileSync(reasonFile, "utf8").trim() : null,
    };
  };
  writeFileSync(join(stubDir, "page-1.json"), JSON.stringify([entry(41), entry(42)]));
  writeFileSync(join(stubDir, "page-2.json"), JSON.stringify([entry(40)]));
}

async function runLore(fixture: Fixture, session: string, args: string[]): Promise<RunResult> {
  const env: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value === undefined || /^(CLAUDE|LORE|ANTHROPIC)/.test(key)) continue;
    env[key] = value;
  }
  const proc = await runLoreInProcess(args, {
    cwd: fixture.dir,
    home: FIXTURE_HOME_OUTSIDE_REPO,
    env: {
      ...env,
      HOME: FIXTURE_HOME_OUTSIDE_REPO,
      CLAUDE_CODE_SESSION_ID: session,
      EDITOR: "true",
      // stub first; the original PATH stays behind it only so `sed`/`cat`/`grep` resolve inside the stub.
      PATH: `${fixture.stubDir}:${process.env["PATH"] ?? ""}`,
    },
  });
  return { stdout: proc.stdout, stderr: proc.stderr, exitCode: proc.exitCode };
}

async function mustRun(fixture: Fixture, session: string, args: string[]): Promise<RunResult> {
  const result = await runLore(fixture, session, args);
  if (result.exitCode !== 0) throw new Error(`lore ${args.join(" ")} failed (${result.exitCode}): ${result.stderr}${result.stdout}`);
  return result;
}

const slugOfCreate = (stdout: string): string => (JSON.parse(stdout) as { data: { slug: string } }).data.slug;

/** `lore done` after a runner-attested pass on an unclaimed task (a claim naming a working copy would arm the not-landed floor, which needs a real `lore integrate`). */
async function completeWithDone(fixture: Fixture, slug: string): Promise<RunResult> {
  await mustRun(fixture, "worker", ["evidence", slug, "--oracle", "test", "--command", "echo 1 passed", "--result", "pass", "--capture"]);
  return await runLore(fixture, "worker", ["done", slug, "--declare-no-new-tests", "fixture: throwaway task"]);
}

/** gh calls that write (PATCH, POST, DELETE) to issue `n`, oldest first. */
function writesTo(fixture: Fixture, n: number): string[] {
  return readLines(join(fixture.stubDir, "gh.log")).filter(
    (line) => line.includes(`repos/${FAKE_REPO}/issues/${n}`) && /-X (PATCH|POST|DELETE)/.test(line),
  );
}

const allWrites = (fixture: Fixture): string[] => readLines(join(fixture.stubDir, "gh.log")).filter((line) => /-X (PATCH|POST|DELETE)/.test(line));
const listingRequests = (fixture: Fixture): string[] => readLines(join(fixture.stubDir, "gh.log")).filter((line) => line.includes("issues?state=all"));
const resetLog = (fixture: Fixture): void => writeFileSync(join(fixture.stubDir, "gh.log"), "");

/** The corpus's own document count, via the real `list` command. */
async function documentCount(fixture: Fixture): Promise<number> {
  const listed = await mustRun(fixture, "setup", ["list", "--json"]);
  const parsed = JSON.parse(listed.stdout) as { data: { docs?: unknown[]; documents?: unknown[] } | unknown[] };
  const data = parsed.data;
  if (Array.isArray(data)) return data.length;
  return (data.docs ?? data.documents ?? []).length;
}

async function makeFixture(): Promise<{ fixture: Fixture; slugs: { forty: string; fortyTwo: string } }> {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), "lore-gs16-corpus-")));
  const stubDir = mkdtempSync(join(tmpdir(), "lore-gs16-stub-"));
  dirsToClean.push(dir, stubDir);
  writeStubGh(stubDir);
  writeFileSync(join(stubDir, "labels-41"), "resolution:adopted\nresolution:fixed\n");
  regenerateListing(stubDir);
  const fixture: Fixture = { dir, stubDir };
  makeCleanTreeRepo(dir);
  await mustRun(fixture, "setup", ["init"]);
  patchLoreConfig(
    dir,
    [
      "workflow:",
      "  gates:",
      "    plan-promote:",
      "      enabled: false",
      "    plan-close:",
      "      enabled: false",
      "  review:",
      "    judgment_required_types: []",
      "feedback:",
      "  upstream:",
      `    repo: ${FAKE_REPO}`,
      "",
    ].join("\n"),
  );
  await mustRun(fixture, "setup", ["create", "prd", "--title", "Sync Fixture PRD", "--no-ai", "--content", "## Overview\n\nBody.", "--json"]);
  const createCarrier = async (title: string, issue: number): Promise<string> =>
    slugOfCreate(
      (await mustRun(fixture, "setup", ["create", "task", "--kind", "code", "--adhoc", "--ac-scope", "", "--title", title, "--no-ai", "--content", "Carrier.", "--issue", String(issue), "--json"])).stdout,
    );
  const forty = await createCarrier("Carrier of forty", 40);
  const fortyTwo = await createCarrier("Carrier of forty-two", 42);
  // #40's close fails at archive time (network), so the archive lands and the issue stays open: close pending.
  writeFileSync(join(stubDir, "fail-patch-40"), "1");
  await completeWithDone(fixture, forty);
  rmSync(join(stubDir, "fail-patch-40"));
  // #42 archives cleanly: the archive step closes it as completed and labels it resolution:fixed.
  await completeWithDone(fixture, fortyTwo);
  regenerateListing(stubDir);
  resetLog({ dir, stubDir });
  return { fixture, slugs: { forty, fortyTwo } };
}

describe(`${SPEC}#AC-GS-16 lore issues --sync is push-only and honest about completeness`, () => {
  let fixture: Fixture;
  let docsBefore = 0;
  // init + create x3 + claim/evidence/done x2 and two reads: an explicit timeout, never the 10s default.
  beforeAll(async () => {
    const made = await makeFixture();
    fixture = made.fixture;
    docsBefore = await documentCount(fixture);
  }, 240_000);

  it(`${SPEC}#AC-GS-16 repairs #40 (page 2) and strips #41's labels, leaves #42 alone, reads each page once`, async () => {
    const result = await runLore(fixture, "worker", ["issues", "--sync"]);
    expect(result.exitCode, result.stderr + result.stdout).toBe(0);
    expect(result.stdout).not.toContain("clean");

    const forty = writesTo(fixture, 40);
    expect(forty.filter((line) => line.includes("-X PATCH") && line.includes("state=closed") && line.includes("state_reason=completed"))).toHaveLength(1);
    expect(forty.filter((line) => line.includes("/comments"))).toHaveLength(1);
    expect(forty.filter((line) => line.includes("/labels") && line.includes("labels[]=resolution:fixed"))).toHaveLength(1);
    expect(forty).toHaveLength(3);

    const fortyOne = writesTo(fixture, 41);
    expect(fortyOne).toHaveLength(2);
    expect(fortyOne.every((line) => line.includes("-X DELETE"))).toBe(true);
    expect(fortyOne.some((line) => line.includes("resolution%3Aadopted"))).toBe(true);
    expect(fortyOne.some((line) => line.includes("resolution%3Afixed"))).toBe(true);

    expect(writesTo(fixture, 42)).toEqual([]);
    expect(listingRequests(fixture)).toHaveLength(2);
  }, 120_000);

  it(`${SPEC}#AC-GS-16 a second run prints clean, exits 0 and makes zero writes; the corpus gained nothing`, async () => {
    regenerateListing(fixture.stubDir);
    resetLog(fixture);
    const result = await runLore(fixture, "worker", ["issues", "--sync"]);
    expect(result.exitCode, result.stderr + result.stdout).toBe(0);
    expect(result.stdout).toContain("clean");
    expect(allWrites(fixture)).toEqual([]);
    expect(listingRequests(fixture)).toHaveLength(2);
    expect(await documentCount(fixture)).toBe(docsBefore);
  }, 120_000);

  it(`${SPEC}#AC-GS-16 a failing page 2 exits 9 and never prints clean`, async () => {
    regenerateListing(fixture.stubDir);
    resetLog(fixture);
    writeFileSync(join(fixture.stubDir, "fail-page-2"), "1");
    try {
      const result = await runLore(fixture, "worker", ["issues", "--sync"]);
      expect(result.exitCode).toBe(9);
      expect(result.stdout).not.toContain("clean");
      expect(allWrites(fixture)).toEqual([]);
    } finally {
      rmSync(join(fixture.stubDir, "fail-page-2"));
    }
  }, 120_000);
});
