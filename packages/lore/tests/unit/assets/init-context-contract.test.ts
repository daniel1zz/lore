// @reads assets/project/CLAUDE.md.template
// @reads assets/skills/lore-init-context/SKILL.md
/**
 * init-context skill + project CLAUDE.md template — SSOT-consumption contract
 * (SPEC-project-claude-md-content-contract-governance-injected, AC-CMC-5).
 *
 * `lore governance claude-md` and `lore status --check-claude-md` are the
 * runtime SSOT for "what goes in a project CLAUDE.md / what stays out" and
 * for drift detection against that contract (see the governing spec). Two
 * consumers currently duplicate or omit that SSOT instead of pointing at it:
 *
 *   1. `assets/skills/lore-init-context/SKILL.md` still carries its OWN
 *      "What Goes In vs What Stays Out" taxonomy (Include/Exclude/
 *      Anti-patterns/Style rules) inline, and never mentions either runtime
 *      command — so a project generated by this skill has no live pointer
 *      back to the governance SSOT, and the skill's prose can silently drift
 *      from it.
 *   2. `assets/project/CLAUDE.md.template`'s managed marker section (the
 *      block every `lore setup --project` install stamps into a fresh
 *      repo's root CLAUDE.md) has no pointer to `lore governance claude-md`
 *      either — so even freshly-scaffolded projects start with zero runtime
 *      linkage to the SSOT.
 *
 * This is the RED half of a paired red/green task: these assertions encode
 * the POST-fix contract and are expected to fail against today's assets.
 * The paired GREEN task (task-skill-implement-template-pointer-lore-init-context-skill)
 * edits `assets/` to make them pass; this file must NOT touch `assets/`.
 *
 * Path resolution follows the sibling `pre-push-parity.test.ts` convention:
 * assets are resolved relative to the repo root (this file lives 5
 * directories below it), never relative to the test file's own directory.
 *
 * Coverage:
 *   HAPPY:      both source assets exist on disk.
 *   NEGATIVE:   a positive-control string proves the `toContain`/
 *               `not.toContain` oracle isn't a tautological always-pass
 *               (i.e. this suite really is reading file content, not a
 *               vacuous truth).
 *   BOUNDARY:   the template's managed-marker pair is well-formed (start
 *               index precedes end index) BEFORE we scan the region between
 *               them for the pointer line — a malformed marker pair would
 *               make the pointer assertion meaningless.
 *   ERROR/RED:  (a) SKILL.md is missing both literal governance commands;
 *               (b) SKILL.md still carries its own taxonomy headings
 *               verbatim; (c) the template's managed section is missing the
 *               pointer line. All three are expected failures today — the
 *               commands/pointer are absent and the taxonomy is still
 *               present, never a test bug.
 *   REGRESSION: the template's pre-existing workflow pointers (e.g.
 *               `lore search <query>`) remain present in the managed
 *               section — proves the fix is additive, not a replacement of
 *               the whole block.
 *
 * @spec_ref AC-CMC-5
 */

import { describe, it, expect } from "vitest";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// ─── Locate the REAL repo-root assets ──────────────────────────────────────
// packages/lore/tests/unit/assets/init-context-contract.test.ts -> repo root
// is 5 levels up from this file's own directory (same convention as
// pre-push-parity.test.ts in this same directory).

const REPO_ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..", "..", "..", "..", "..");
const SKILL_PATH = join(REPO_ROOT, "assets", "skills", "lore-init-context", "SKILL.md");
const TEMPLATE_PATH = join(REPO_ROOT, "assets", "project", "CLAUDE.md.template");

const MANAGED_START_MARKER = "# ─── lore governance (managed) ───";
const MANAGED_END_MARKER = "# ─── end lore governance ───";

describe("init-context skill + CLAUDE.md template — governance SSOT-consumption pins (RED)", () => {
  it("HAPPY: both source assets exist on disk", () => {
    expect(existsSync(SKILL_PATH)).toBe(true);
    expect(existsSync(TEMPLATE_PATH)).toBe(true);
  });

  it("NEGATIVE: the content-scan oracle is not a tautological always-pass (positive control)", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    // A string we know is present today in SKILL.md's own heading — proves
    // toContain genuinely reads file content rather than vacuously passing.
    expect(skillContent).toContain("# Context Layer Initialization");
  });

  it("RED (scenario 1a): SKILL.md is missing the literal command `lore governance claude-md`", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    expect(skillContent).toContain("lore governance claude-md");
  });

  it("RED (scenario 1b): SKILL.md is missing the literal command `lore status --check-claude-md`", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    expect(skillContent).toContain("lore status --check-claude-md");
  });

  it("RED (scenario 2a): SKILL.md still carries its own taxonomy section heading", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    expect(skillContent).not.toContain("## What Goes In vs What Stays Out");
  });

  it("RED (scenario 2b): SKILL.md still carries its own 'Include' taxonomy subheading", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    expect(skillContent).not.toContain("### Include (static knowledge — changes monthly or less)");
  });

  it("RED (scenario 2c): SKILL.md still carries its own 'Exclude' taxonomy subheading", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    expect(skillContent).not.toContain("### Exclude (dynamic state, noise, or code-readable details)");
  });

  it("RED (scenario 2d): SKILL.md still carries its own 'Anti-patterns' taxonomy subheading", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    expect(skillContent).not.toContain("### Anti-patterns (observed from real runs — avoid these)");
  });

  it("RED (scenario 2e): SKILL.md still carries its own 'Style rules' taxonomy subheading", () => {
    const skillContent = readFileSync(SKILL_PATH, "utf8");
    expect(skillContent).not.toContain("### Style rules");
  });

  it("BOUNDARY: the template's managed marker pair is well-formed before scanning between them", () => {
    const template = readFileSync(TEMPLATE_PATH, "utf8");
    const startIdx = template.indexOf(MANAGED_START_MARKER);
    const endIdx = template.indexOf(MANAGED_END_MARKER);
    expect(startIdx).toBeGreaterThanOrEqual(0);
    expect(endIdx).toBeGreaterThan(startIdx);
  });

  it("RED (scenario 3): the template's managed section is missing a pointer to `lore governance claude-md`", () => {
    const template = readFileSync(TEMPLATE_PATH, "utf8");
    const startIdx = template.indexOf(MANAGED_START_MARKER);
    const endIdx = template.indexOf(MANAGED_END_MARKER);
    const managedSection = template.slice(startIdx, endIdx);
    expect(managedSection).toContain("lore governance claude-md");
  });

  it("REGRESSION: the template's pre-existing workflow pointers remain present in the managed section", () => {
    const template = readFileSync(TEMPLATE_PATH, "utf8");
    const startIdx = template.indexOf(MANAGED_START_MARKER);
    const endIdx = template.indexOf(MANAGED_END_MARKER);
    const managedSection = template.slice(startIdx, endIdx);
    expect(managedSection).toContain("lore search <query>");
    expect(managedSection).toContain("lore status");
  });
});
