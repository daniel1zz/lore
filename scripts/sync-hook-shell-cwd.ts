#!/usr/bin/env bun
/**
 * Generates `assets/hooks/lib/shell-cwd.mjs` — the git-safety hook's copy of the shared shell-cwd parser —
 * from its single source, `packages/core/src/shell-cwd.ts` (`bun run check:hook-shell-cwd` proves them identical).
 *
 * Purpose: the shipped hook assets are standalone `.mjs` files with no access to `@lore/core` at runtime, so
 * the one parser (spec-defect-clusters-round-1-done-floors-judge-real-runs-on D4) reaches the hook as a
 * GENERATED copy, never a hand-written second implementation. Edit the `.ts`, rerun this script, then
 * `bun scripts/embed-assets-manifest.mjs` (the copy is a hashed asset).
 *
 * Public surface: {@link renderHookShellCwd}, {@link HOOK_SHELL_CWD_PATH}; CLI `bun scripts/sync-hook-shell-cwd.ts [--check]`.
 * Side-effect class: IO (reads the source; writes the copy unless `--check`). `--check` never writes and exits 1 on drift.
 * Deterministic: TypeScript's own `transpileModule` output plus a fixed banner — no timestamps.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SHELL_CWD_SOURCE_PATH = join(REPO_ROOT, "packages", "core", "src", "shell-cwd.ts");
export const HOOK_SHELL_CWD_PATH = join(REPO_ROOT, "assets", "hooks", "lib", "shell-cwd.mjs");

const BANNER =
  "// GENERATED by scripts/sync-hook-shell-cwd.ts from packages/core/src/shell-cwd.ts — DO NOT EDIT.\n" +
  "// Single source: packages/core/src/shell-cwd.ts. Regenerate: bun scripts/sync-hook-shell-cwd.ts\n" +
  "// Verified identical by: bun scripts/sync-hook-shell-cwd.ts --check\n";

/**
 * @returns the exact text `assets/hooks/lib/shell-cwd.mjs` must contain for the current `shell-cwd.ts`
 */
export function renderHookShellCwd(): string {
  const source = readFileSync(SHELL_CWD_SOURCE_PATH, "utf8");
  const output = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      removeComments: false,
      newLine: ts.NewLineKind.LineFeed,
    },
    fileName: "shell-cwd.ts",
  });
  return BANNER + output.outputText;
}

function main(argv: readonly string[]): number {
  const expected = renderHookShellCwd();
  if (argv.includes("--check")) {
    let actual = "";
    try {
      actual = readFileSync(HOOK_SHELL_CWD_PATH, "utf8");
    } catch {
      process.stderr.write(`hook shell-cwd copy missing: ${HOOK_SHELL_CWD_PATH}\n`); // CLI surface
      return 1;
    }
    if (actual !== expected) {
      process.stderr.write("assets/hooks/lib/shell-cwd.mjs drifted from packages/core/src/shell-cwd.ts — run: bun scripts/sync-hook-shell-cwd.ts\n"); // CLI surface
      return 1;
    }
    process.stdout.write("hook shell-cwd copy OK\n"); // CLI surface
    return 0;
  }
  writeFileSync(HOOK_SHELL_CWD_PATH, expected);
  process.stdout.write(`wrote ${HOOK_SHELL_CWD_PATH}\n`); // CLI surface
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
