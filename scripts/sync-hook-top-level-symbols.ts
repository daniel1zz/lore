#!/usr/bin/env bun
/**
 * Generates `assets/hooks/lib/top-level-symbols.mjs` — the pre-edit anchor gate's copy of the top-level symbol extraction —
 * from its single source, `packages/core/src/top-level-symbols.ts` (`bun run check:hook-top-level-symbols` proves them identical).
 *
 * Purpose: the shipped hook assets are standalone `.mjs` files with no access to `@lore/core` at runtime, so
 * the one extraction (also used by `lore integrate`'s own-diff judgment, spec
 * spec-a-branch-s-own-diff-is-judged-at-integrate-the-turn-end) reaches the hook as a
 * GENERATED copy, never a hand-written second implementation. Edit the `.ts`, rerun this script, then
 * `bun scripts/embed-assets-manifest.mjs` (the copy is a hashed asset).
 *
 * Public surface: {@link renderHookTopLevelSymbols}, {@link HOOK_TOP_LEVEL_SYMBOLS_PATH}; CLI `bun scripts/sync-hook-top-level-symbols.ts [--check]`.
 * Side-effect class: IO (reads the source; writes the copy unless `--check`). `--check` never writes and exits 1 on drift.
 * Deterministic: TypeScript's own `transpileModule` output plus a fixed banner — no timestamps.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const TOP_LEVEL_SYMBOLS_SOURCE_PATH = join(REPO_ROOT, "packages", "core", "src", "top-level-symbols.ts");
export const HOOK_TOP_LEVEL_SYMBOLS_PATH = join(REPO_ROOT, "assets", "hooks", "lib", "top-level-symbols.mjs");

const BANNER =
  "// GENERATED by scripts/sync-hook-top-level-symbols.ts from packages/core/src/top-level-symbols.ts — DO NOT EDIT.\n" +
  "// Single source: packages/core/src/top-level-symbols.ts. Regenerate: bun scripts/sync-hook-top-level-symbols.ts\n" +
  "// Verified identical by: bun scripts/sync-hook-top-level-symbols.ts --check\n";

/**
 * @returns the exact text `assets/hooks/lib/top-level-symbols.mjs` must contain for the current `top-level-symbols.ts`
 */
export function renderHookTopLevelSymbols(): string {
  const source = readFileSync(TOP_LEVEL_SYMBOLS_SOURCE_PATH, "utf8");
  const output = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      removeComments: false,
      newLine: ts.NewLineKind.LineFeed,
    },
    fileName: "top-level-symbols.ts",
  });
  return BANNER + output.outputText;
}

function main(argv: readonly string[]): number {
  const expected = renderHookTopLevelSymbols();
  if (argv.includes("--check")) {
    let actual = "";
    try {
      actual = readFileSync(HOOK_TOP_LEVEL_SYMBOLS_PATH, "utf8");
    } catch {
      process.stderr.write(`hook top-level-symbols copy missing: ${HOOK_TOP_LEVEL_SYMBOLS_PATH}\n`); // CLI surface
      return 1;
    }
    if (actual !== expected) {
      process.stderr.write("assets/hooks/lib/top-level-symbols.mjs drifted from packages/core/src/top-level-symbols.ts — run: bun scripts/sync-hook-top-level-symbols.ts\n"); // CLI surface
      return 1;
    }
    process.stdout.write("hook top-level-symbols copy OK\n"); // CLI surface
    return 0;
  }
  writeFileSync(HOOK_TOP_LEVEL_SYMBOLS_PATH, expected);
  process.stdout.write(`wrote ${HOOK_TOP_LEVEL_SYMBOLS_PATH}\n`); // CLI surface
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
